function result=legacy_pid()
% Numerical core extracted from arm_PID.m.
% Historical arithmetic is retained, not a corrected fair-comparison model.
ts=0.001;
T=20;
n=T/ts;
q_1=[0.5;0.55];
dq_1=[0;0];
ddq_1=[0;0];
tao_1=[0;0];
m1=0.3; m2=0.5;
l1=0.2; l2=0.3;
J1=0.05; J2=0.1;
g=9.81;
a=2;
b=0.8;
kp1=100; ki1=5; kd1=4;
kp2=100; ki2=10; kd2=2;
kp=[kp1,0;
    0,kp2];
ki=[ki1,0;
    0,ki2];
kd=[kd1,0;
    0,kd2];
sum_e_1=[0;0];
e_1=[0;0];
sume1_PID=0; sume2_PID=0;
for k=1:1:n
    timef(k)=ts*k;
    d1(k)=0.2*sin(2*timef(k))+0.1*sin(4*timef(k))+0.05*cos(1.5*timef(k));
    d2(k)=0.02*cos(1.5*timef(k))+0.3*sin(2*timef(k))+0.05*cos(0.5*timef(k));
    d(:,k)=[d1(k);d2(k)]*15;
    q1_1=q_1(1);
    q2_1=q_1(2);
    dq1_1=dq_1(1);
    dq2_1=dq_1(2);
    h11=(m1+m2)*l1^2+m2*l2^2+2*m2*l1*l2*cos(q2_1)+J1;
    h12=m2*l2^2+m2*l1*l2*cos(q2_1);
    h21=h12;
    h22=m2*l2^2+J2;
    H=[h11,h12;
        h21,h22];
    c11=-m2*l1*l2*sin(q2_1)*dq2_1;
    c12=-m2*l1*l2*sin(q2_1)*(dq1_1-dq2_1);
    c21=0;
    c22=m2*l1*l2*sin(q2_1)*dq1_1;
    C=[c11,c12;
        c21,c22];
    g1=(m1+m2)*g*l1*cos(q1_1)+m2*g*l2*cos(q1_1+q2_1);
    g2=m2*g*l2*cos(q1_1+q2_1);
    G=[g1;g2];
    yd1(k)=sin(a*timef(k));
    yd2(k)=sin(b*timef(k));
    yd(:,k)=[yd1(k);yd2(k)];
    q_PID(:,k)=q_1+dq_1*ts;
    dq(:,k)=dq_1+ddq_1*ts;
    ddq(:,k)=inv(H)*(tao_1+d(:,k)-G-C*dq_1+d(:,k));
    e(:,k)=yd(:,k)-q_PID(:,k);
    sum_e(:,k)=sum_e_1+e(:,k)*ts;
    de(:,k)=(e(:,k)-e_1)/ts;
    tao_PID(:,k)=kp*e(:,k)+ki*sum_e(:,k)+kd*de(:,k);
    tao_1=tao_PID(:,k);
    q_1=q_PID(:,k);
    dq_1=dq(:,k);
    ddq_1=ddq(:,k);
    e_1=e(:,k);
    sum_e_1=sum_e(:,k);
    qe1_PID(k)=sume1_PID+abs(yd1(k)-q_PID(1,k));
    sume1_PID=qe1_PID(k);
    qe2_PID(k)=sume2_PID+abs(yd2(k)-q_PID(2,k));
    sume2_PID=qe2_PID(k);
end
result=struct();
result.timef=timef;
result.yd=yd;
result.q_PID=q_PID;
result.tao_PID=tao_PID;
result.qe1_PID=qe1_PID;
result.qe2_PID=qe2_PID;
end
